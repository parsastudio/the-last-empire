function calculateHybridGdpMap(): Record<string, number> {
  const result: Record<string, number> = {};
  const allCodes = Array.from(
    new Set([
      ...Object.keys(COUNTRY_NOMINAL_GDP_MAP),
      ...Object.keys(COUNTRY_PPP_GDP_MAP),
    ]),
  );

  for (let i = 0; i < allCodes.length; i++) {
    const code = allCodes[i]!;
    const nominal = COUNTRY_NOMINAL_GDP_MAP[code] ?? 50_000_000_000;
    const ppp = COUNTRY_PPP_GDP_MAP[code] ?? nominal;
    result[code] = Math.floor(0.5 * nominal + 0.5 * ppp);
  }

  return result;
}

